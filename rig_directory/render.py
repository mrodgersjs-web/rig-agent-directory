"""Render the markdown index and the README generated blocks from a catalog.

Three generated surfaces, all derived from the catalog entries:

  * ``INDEX.md``  — the full entry tables, split into original and adapted agents.
  * the README **counts** block — the by-kind totals, split by origin.
  * the README **attribution** block — the plain-English statement of what is
    adapted from where, and under which license.

Nothing here reads ``data/attribution.json`` directly; it reads the ``source``
block already stamped on each entry, so the docs can never claim more or less
than the catalog holds.
"""
from __future__ import annotations

from collections import Counter

START = "<!-- counts:start (generated by `rig-directory readme`; do not edit by hand) -->"
END = "<!-- counts:end -->"
ATTRIBUTION_START = "<!-- attribution:start (generated by `rig-directory readme`; do not edit by hand) -->"
ATTRIBUTION_END = "<!-- attribution:end -->"


def _cell(text: str, limit: int = 140) -> str:
    text = " ".join(str(text).split()).replace("|", "\\|")
    return text if len(text) <= limit else text[: limit - 1].rstrip() + "…"


def _attributed(c: dict) -> list[dict]:
    return [a for a in c["agents"] if a.get("source")]


def _original(c: dict) -> list[dict]:
    return [a for a in c["agents"] if not a.get("source")]


def _banner(c: dict) -> list[str]:
    """The plain-English attribution statement, rendered from the entries."""
    adapted = _attributed(c)
    if not adapted:
        return []
    groups: dict[tuple[str, str], list[dict]] = {}
    for a in adapted:
        groups.setdefault((a["source"]["upstream_owner"], a["source"]["upstream_repo"]), []).append(a)
    out = ["## Attribution", ""]
    for (owner, repo), items in sorted(groups.items()):
        src = items[0]["source"]
        repos = sorted({i["repo"] for i in items})
        listed = ", ".join(f"[`{r}`](https://github.com/{c['owner']}/{r})" for r in repos)
        out.append(
            f"The **{len(items)} agent role specs** in {listed} are **adapted from "
            f"[{owner}/{repo}]({src['upstream_url']})** and licensed under {src['license']} "
            f"([license text]({src['license_url']})). They are **not original work** by the "
            f"catalog owner."
        )
        out += ["", f"> {src['note']}", ""]
    n = c["counts"]
    out.append(
        f"Of the {n['agents']} agent entries in this catalog, **{n['agents_attributed']} are adapted** "
        f"from upstream work and **{n['agents_original']} are original** to the catalog owner's repos. "
        f"Both are listed below, separately."
    )
    out.append("")
    return out


def _agent_tables(items: list[dict]) -> list[str]:
    by_dept: dict[str, list[dict]] = {}
    for a in items:
        by_dept.setdefault(a["department"] or "(none)", []).append(a)
    rows: list[str] = []
    for dept, group in by_dept.items():
        rows += [f"### {dept} ({len(group)})", "", "| Agent | Repo | Description |", "|---|---|---|"]
        for a in group:
            rows.append(f"| [{_cell(a['name'])}]({a['url']}) | {a['repo']} | {_cell(a['description'])} |")
        rows.append("")
    return rows


def render_index(c: dict) -> str:
    n = c["counts"]
    out = [
        "# RIG Agent Directory: generated index",
        "",
        "Generated by `rig-directory index` from `catalog/catalog.json`. Do not edit by hand.",
        "",
        f"{n['repos']} public repos ({n['repos_crawled']} crawled), {n['skills']} skills, "
        f"{n['engines']} deviation engines, and {n['agents']} agent role specs "
        f"({n['agents_original']} original, {n['agents_attributed']} adapted from upstream).",
        "",
    ]
    out += _banner(c)
    out += [
        "## Repos",
        "",
        "| Repo | Origin | Skills | Agents | Engines | Test files | Description |",
        "|---|---|---|---|---|---|---|",
    ]
    adapted_repos = {a["repo"] for a in _attributed(c)}
    for r in c["repos"]:
        origin = "adapted from upstream" if r["name"] in adapted_repos else "original"
        if r["fork"]:
            origin += " (fork, not crawled)"
        k = r["counts"]
        out.append(
            f"| [{r['name']}]({r['url']}) | {origin} | {k['skills']} | {k['agents']} | {k['engines']} | "
            f"{r['test_files']} | {_cell(r['description'])} |"
        )
    out += ["", "## Skills", "", "| Skill | Pack | Repo | Description |", "|---|---|---|---|"]
    for s in c["skills"]:
        out.append(f"| [{_cell(s['name'])}]({s['url']}) | {s['pack'] or ''} | {s['repo']} | {_cell(s['description'])} |")

    original = _original(c)
    out += ["## Agents (original)", ""]
    out += (
        [f"Original to the catalog owner's repos ({len(original)} entries).", ""] + _agent_tables(original)
        if original
        else ["No original agent entries in this catalog.", ""]
    )

    adapted = _attributed(c)
    out += ["## Agents (adapted from upstream)", ""]
    if adapted:
        src = adapted[0]["source"]
        out += [
            f"Adapted from [{src['upstream_owner']}/{src['upstream_repo']}]({src['upstream_url']}) "
            f"under the {src['license']} license. Not original work by the catalog owner.",
            "",
        ]
        out += _agent_tables(adapted)
    else:
        out += ["No adapted agent entries in this catalog.", ""]

    out += ["## Deviation engines", "", "| # | Codename | Layer | Full name | Description |", "|---|---|---|---|---|"]
    for e in c["engines"]:
        out.append(
            f"| {e['id']} | [{e['codename']}]({e['url']}) | {e['layer']} | "
            f"{_cell(e['full_name'])} | {_cell(e['description'])} |"
        )
    return "\n".join(out) + "\n"


def render_counts_block(c: dict) -> str:
    n = c["counts"]
    lines = [
        START,
        f"Counted from `catalog/catalog.json` ({n['repos']} public repos listed, {n['repos_crawled']} crawled):",
        "",
        "| Kind | Count |",
        "|---|---|",
        f"| Public repos | {n['repos']} |",
        f"| Skills | {n['skills']} ({n['skills_unique_names']} unique names) |",
        f"| Deviation engines | {n['engines']} |",
        "",
    ]
    if n.get("agents_attributed"):
        lines += [
            f"**Agents, split by origin:** {n['agents_original']} original to the catalog owner's repos; "
            f"{n['agents_attributed']} adapted from upstream work and not original. "
            f"{n['agents']} entries total ({n['agents_unique_names']} unique names). "
            f"The adapted ones are listed separately in [INDEX.md](INDEX.md#agents-adapted-from-upstream) "
            f"and stated plainly in [Attribution](#attribution).",
            "",
            "| Agents | Count |",
            "|---|---|",
            f"| Original to the catalog owner's repos | {n['agents_original']} |",
            f"| Adapted from upstream (not original) | {n['agents_attributed']} |",
            "",
        ]
    else:
        lines += [f"| Agents | {n['agents']} ({n['agents_unique_names']} unique names) |", ""]
    original_depts = Counter(a["department"] or "(none)" for a in _original(c))
    adapted_depts = Counter(a["department"] or "(none)" for a in _attributed(c))
    layers = Counter(e["layer"] for e in c["engines"])
    if original_depts:
        lines.append(
            "Original agents by department: "
            + ", ".join(f"{d} {k}" for d, k in sorted(original_depts.items()))
            + "."
        )
        lines.append("")
    if adapted_depts:
        lines.append(
            "Adapted agents by department: "
            + ", ".join(f"{d} {k}" for d, k in sorted(adapted_depts.items()))
            + "."
        )
        lines.append("")
    if layers:
        lines.append("Engines by layer: " + ", ".join(f"{d} {k}" for d, k in sorted(layers.items())) + ".")
        lines.append("")
    lines.append(END)
    return "\n".join(lines)


def render_attribution_block(c: dict) -> str:
    banner = _banner(c)
    if not banner:
        return ""
    # No trailing newline: the block must end exactly at the end marker, or
    # each `rig-directory readme` run would append one more blank line.
    return "\n".join([ATTRIBUTION_START] + banner + [ATTRIBUTION_END])


def _replace(text: str, start: str, end: str, block: str) -> str:
    if start in text and end in text:
        head, rest = text.split(start, 1)
        _, tail = rest.split(end, 1)
        return head + block + tail
    raise ValueError(f"README has no markers for {start}")


def update_readme(readme: str, c: dict) -> str:
    """Refresh the counts block, then the attribution block. Both are required."""
    text = _replace(readme, START, END, render_counts_block(c))
    block = render_attribution_block(c)
    if not block:
        raise ValueError("catalog has attributed entries but the README has no attribution markers")
    return _replace(text, ATTRIBUTION_START, ATTRIBUTION_END, block)
